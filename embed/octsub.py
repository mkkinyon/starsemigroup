"""Search for a regular *-semigroup satisfying the hexagon condition but not the
(cyclic) octagon condition, as a quotient of a *-subsemigroup of P_n.

Plan: choose projections a1..a4, b1..b4 of P_n with
   a_i a_j = a_j a_i, b_i b_j = b_j b_i, a_i b_i = b_i a_i, a_i |><| b_{i+-1},
   a_i, b_{i+2} neither matched nor commuting (general position);
let S = <a's, b's> (a *-subsemigroup), rho = the *-congruence of S generated by
identifying all a_i a_j (i != j) and all b_i b_j; require [a1 a2] != [b1 b2] in S/rho,
and then test the hexagon condition on the projection algebra of S/rho.
"""
import sys, time, itertools, pickle, re
from pmon import Pn, projections, rank, canon, star as pstar
from termeval import make_eval

n = int(sys.argv[1]) if len(sys.argv) > 1 else 4
P = Pn(n)
projs = projections(n)
pi = {p: i for i, p in enumerate(projs)}
M = len(projs)
print(f"P_{n}: {M} projections", flush=True)

mulp = [[P.mul(p, q) for q in projs] for p in projs]
commute = [[mulp[i][j] == mulp[j][i] for j in range(M)] for i in range(M)]
matched = [[P.mul(mulp[i][j], projs[i]) == projs[i] and P.mul(mulp[j][i], projs[j]) == projs[j]
            for j in range(M)] for i in range(M)]
# symmetry: S_n acting on projections
def act(perm, p):
    return canon([[perm[x] if x < n else n + perm[x - n] for x in blk] for blk in p])
perms = list(itertools.permutations(range(n)))
seen = set(); reps = []
for i, p in enumerate(projs):
    if i in seen: continue
    reps.append(i)
    for perm in perms:
        seen.add(pi[act(perm, p)])

def general(i, j):
    return not matched[i][j] and not commute[i][j] and i != j

GENERAL = "--relax" not in sys.argv
COINC = "--coinc" in sys.argv        # allow coincidences among the eight vertices
def general(i, j):
    if not GENERAL:
        return COINC or i != j
    return not matched[i][j] and not commute[i][j] and i != j
def distinct(x, *others):
    return COINC or x not in others

comm = [set(j for j in range(M) if commute[i][j] and (COINC or j != i)) for i in range(M)]
mat = [set(j for j in range(M) if matched[i][j] and (COINC or j != i)) for i in range(M)]

def candidates():
    """yield index tuples (a1,a2,a3,a4,b1,b2,b3,b4); order: a1, b2, b4, a3, a2, b1, b3, a4"""
    for a1 in reps:
        for b2 in mat[a1]:
            for b4 in mat[a1] & comm[b2]:
                if not distinct(b4, b2): continue
                for a3 in mat[b2] & mat[b4] & comm[a1]:
                    for a2 in comm[a1] & comm[a3] & comm[b2]:
                        if not distinct(a2, a1, a3) or not general(a2, b4): continue
                        for b1 in mat[a2] & comm[b2] & comm[b4]:
                            if not distinct(b1, b2, b4) or not general(a3, b1): continue
                            for b3 in mat[a2] & comm[b1] & comm[b2] & comm[b4]:
                                if not distinct(b3, b1, b2, b4) or not general(a1, b3): continue
                                for a4 in mat[b1] & mat[b3] & comm[a1] & comm[a2] & comm[a3] & comm[b4]:
                                    if not distinct(a4, a1, a2, a3) or not general(a4, b2): continue
                                    yield (a1, a2, a3, a4, b1, b2, b3, b4)

def generate(gens):
    """*-subsemigroup generated (as a list of partitions), plus index maps."""
    S = list(dict.fromkeys(gens)); idx = {x: i for i, x in enumerate(S)}
    frontier = list(S)
    while frontier:
        new = []
        for x in frontier:
            for y in list(S):
                for z in (P.mul(x, y), P.mul(y, x)):
                    if z not in idx:
                        idx[z] = len(S); S.append(z); new.append(z)
        frontier = new
    return S, idx

class UF:
    def __init__(self, k): self.p = list(range(k))
    def find(self, x):
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]; x = self.p[x]
        return x
    def union(self, a, b):
        a, b = self.find(a), self.find(b)
        if a == b: return False
        self.p[a] = b; return True

def star_congruence(S, idx, pairs):
    """smallest *-congruence on S containing the pairs (as indices)."""
    k = len(S)
    T = [[idx[P.mul(x, y)] for y in S] for x in S]
    st = [idx[pstar(x, n)] for x in S]
    uf = UF(k); todo = list(pairs)
    while todo:
        a, b = todo.pop()
        if not uf.union(a, b): continue
        todo.append((st[a], st[b]))
        for c in range(k):
            todo.append((T[a][c], T[b][c])); todo.append((T[c][a], T[c][b]))
    return uf, T, st

HEX = """x1 * x2 != x2 * x3 | x1 * x2 != x3 * x1 |
y1 * y2 != y2 * y3 | y1 * y2 != y3 * y1 |
x1 * y1 != y1 * x1 | x2 * y2 != y2 * x2 | x3 * y3 != y3 * x3 |
y2 * x1 != x1 | x1 * y2 != y2 | y3 * x1 != x1 | x1 * y3 != y3 |
y1 * x2 != x2 | x2 * y1 != y1 | y3 * x2 != x2 | x2 * y3 != y3 |
y1 * x3 != x3 | x3 * y1 != y1 | y2 * x3 != x3 | x3 * y2 != y2 |
x1 * x2 = y1 * y2."""
def parse_clause(text):
    lits = []
    for lit in text.strip().rstrip(".").split("|"):
        lit = lit.strip()
        if "!=" in lit: l, r = lit.split("!="); lits.append((l.strip(), r.strip(), True))
        else: l, r = lit.split("="); lits.append((l.strip(), r.strip(), False))
    return lits
hexlits = parse_clause(HEX)

def search_clause(lits, dom, op):
    ev = make_eval(op)
    vars_ = sorted({v for l, r, _ in lits for v in re.findall(r"[xy]\d", l + " " + r)})
    hyps = [(l, r) for l, r, neg in lits if neg]; concl = [(l, r) for l, r, neg in lits if not neg]
    stage = [[] for _ in vars_]
    for l, r in hyps:
        vs = set(re.findall(r"[xy]\d", l + " " + r)); stage[max(vars_.index(v) for v in vs)].append((l, r))
    out = []
    def rec(k, env):
        if out: return
        if k == len(vars_):
            if all(ev(l, env) != ev(r, env) for l, r in concl): out.append(dict(env))
            return
        for p in dom:
            if p in env.values(): continue
            env[vars_[k]] = p
            if all(ev(l, env) == ev(r, env) for l, r in stage[k]): rec(k + 1, env)
        del env[vars_[k]]
    rec(0, {})
    return out

t0 = time.time(); ncand = 0; results = []
for cand in candidates():
    ncand += 1
    if ncand % 2000 == 0:
        print(f"  ... {ncand} candidates, {time.time()-t0:.0f}s", flush=True)
    if mulp[cand[0]][cand[1]] == mulp[cand[4]][cand[5]]:
        continue
    gens = [projs[i] for i in cand]
    S, idx = generate(gens)
    A = [idx[projs[i]] for i in cand[:4]]; B = [idx[projs[i]] for i in cand[4:]]
    Tfull = None
    prods_a = [idx[P.mul(S[A[i]], S[A[j]])] for i in range(4) for j in range(4) if i != j]
    prods_b = [idx[P.mul(S[B[i]], S[B[j]])] for i in range(4) for j in range(4) if i != j]
    pairs = [(prods_a[0], x) for x in prods_a[1:]] + [(prods_b[0], x) for x in prods_b[1:]]
    uf, T, st = star_congruence(S, idx, pairs)
    w, z = uf.find(prods_a[0]), uf.find(prods_b[0])
    if w == z:
        continue
    # quotient projection algebra
    k = len(S)
    cl = {}
    for x in range(k):
        cl.setdefault(uf.find(x), x)
    classes = sorted(cl)
    qi = {c: i for i, c in enumerate(classes)}
    nq = len(classes)
    Tq = [[qi[uf.find(T[cl[c]][cl[d]])] for d in classes] for c in classes]
    sq = [qi[uf.find(st[cl[c]])] for c in classes]
    projq = [x for x in range(nq) if sq[x] == x and Tq[x][x] == x]
    op = lambda x, y, Tq=Tq: Tq[Tq[y][x]][y]
    ce = search_clause(hexlits, projq, op)
    print(f"cand #{ncand}: |S|={k}, |S/rho|={nq}, {len(projq)} projections, w!=z, hexagon counterexamples: {'yes' if ce else 'NO'}  ({time.time()-t0:.0f}s)", flush=True)
    results.append((cand, k, nq, len(projq), bool(ce)))
    if not ce:
        print("   *** SEPARATING EXAMPLE ***", [projs[i] for i in cand])
        pickle.dump((cand, S, [uf.find(x) for x in range(k)]), open(f"octsep_{n}.pkl", "wb"))
        break
print(f"{ncand} candidates examined ({time.time()-t0:.0f}s)")
