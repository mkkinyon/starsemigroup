"""All *-congruences of P_n contained in mu_{S_2} (the largest *-congruence without a zero, cf. p4cong.py),
computed as joins of principal congruences generated by pairs inside mu_{S_2}; test Q1 and the triangle
condition on each proper quotient.  Usage: python3 p4cong2.py n"""
import sys, time, itertools
from collections import defaultdict
from pmon import partition_monoid, mul, star, rank, canon, is_projection
from digraph import clause, parse_clause, search

n = int(sys.argv[1])
elems = partition_monoid(n); idx = {e: i for i, e in enumerate(elems)}
N = len(elems); rk = [rank(e, n) for e in elems]
perm = list(range(n)); perm[0], perm[1] = 1, 0
cyc = [(i + 1) % n for i in range(n)]
gens = [canon([[i, n + perm[i]] for i in range(n)]), canon([[i, n + cyc[i]] for i in range(n)]),
        canon([[0, 1, n, n + 1]] + [[i, n + i] for i in range(2, n)]), canon([[0], [n]] + [[i, n + i] for i in range(1, n)])]
L = [[idx[mul(g, e, n)] for e in elems] for g in gens]     # L[g][x] = g x
R = [[idx[mul(e, g, n)] for e in elems] for g in gens]
ST = [idx[star(e, n)] for e in elems]
print(f"P_{n}: {N} elements; tables done", flush=True)

def closure(pairs, base=None):
    par = list(base) if base else list(range(N))
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    queue = list(pairs)
    while queue:
        a, b = queue.pop()
        ra, rb = find(a), find(b)
        if ra == rb: continue
        par[ra] = rb
        queue.append((ST[a], ST[b]))
        for g in range(len(gens)):
            queue.append((L[g][a], L[g][b])); queue.append((R[g][a], R[g][b]))
    return tuple(find(x) for x in range(N))

def canon_part(part):
    m = {}; return tuple(m.setdefault(x, len(m)) for x in part)

def hat(p):
    out = []
    for b in p:
        up = [x for x in b if x < n]; lo = [x for x in b if x >= n]
        if up and lo: out += [tuple(up), tuple(lo)]
        else: out.append(tuple(b))
    return tuple(sorted(out))

# classes of mu_{S_2}
key = {}; cls = list(range(N))
for i, e in enumerate(elems):
    if rk[i] <= 1: k = ("hat", hat(e))
    elif rk[i] == 2:
        up = tuple(sorted(tuple(x for x in b if x < n) for b in e if any(x < n for x in b)))
        lo = tuple(sorted(tuple(x for x in b if x >= n) for b in e if any(x >= n for x in b)))
        tu = tuple(sorted(tuple(x for x in b if x < n) for b in e if any(x < n for x in b) and any(x >= n for x in b)))
        tl = tuple(sorted(tuple(x for x in b if x >= n) for b in e if any(x < n for x in b) and any(x >= n for x in b)))
        k = ("H", up, lo, tu, tl)
    else: k = ("id", i)
    key.setdefault(k, i); cls[i] = key[k]
groups = defaultdict(list)
for i in range(N): groups[cls[i]].append(i)
pairs = [(m[0], x) for m in groups.values() for x in m[1:]]
print(f"mu_S2: {len(set(cls))} classes, {len(pairs)} generating pairs", flush=True)
t = time.time()
principal = {}
for a, b in pairs:
    c = canon_part(closure([(a, b)]))
    principal.setdefault(c, (a, b))
print(f"{len(principal)} distinct principal congruences ({time.time()-t:.0f}s)", flush=True)
congs = set(principal)
frontier = list(principal)
while frontier:
    new = []
    for c in frontier:
        for p in principal:
            first = {}
            cpairs = []
            for i in range(N):
                if c[i] in first: cpairs.append((first[c[i]], i))
                else: first[c[i]] = i
            j = canon_part(closure([principal[p]] + cpairs))
            if j not in congs: congs.add(j); new.append(j)
    frontier = new
congs.add(canon_part(tuple(range(N))))
print(f"{len(congs)} *-congruences contained in mu_S2 (including Delta)", flush=True)

for c in sorted(congs, key=lambda c: -len(set(c))):
    K0 = len(set(c))
    if K0 == N: print(f"  Delta ({N} classes)"); continue
    rep = {}
    for i, x in enumerate(c): rep.setdefault(x, i)
    projs = sorted({c[i] for i, e in enumerate(elems) if is_projection(e, n)})
    pidx = {x: k for k, x in enumerate(projs)}
    def theta(x, y):
        ex, ey = elems[rep[x]], elems[rep[y]]
        return c[idx[mul(mul(ey, ex, n), ey, n)]]
    T = [[pidx[theta(projs[a], projs[b])] for b in range(len(projs))] for a in range(len(projs))]
    K = len(projs)
    q1 = all(T[p][q] == T[q][p] for p in range(K) for q in range(K) if any(T[r][p] == r and T[r][q] == r for r in range(K)))
    tri = search(parse_clause(clause(3, [(1, 2), (2, 3), (3, 1)])), range(K), lambda x, y: T[x][y], limit=3000)
    sizes = sorted((len(g) for g in defaultdict(list, {x: [i for i in range(N) if c[i] == x] for x in set(c)}).values()), reverse=True)[:3]
    print(f"  quotient with {K0} classes (largest classes {sizes}), {K} projections: Q1={q1}, triangle {'holds' if tri == [] else ('timeout' if tri == 'timeout' else 'FAILS')}", flush=True)
