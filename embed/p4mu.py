"""Projection algebra of P_4/mu_1 (mu_1: rank<=1 elements with equal ker and coker are
identified) and exhaustive search for hexagon / octagon counterexamples in it.
Also: the subalgebra generated by an octagon configuration, and whether the hexagon
condition holds there."""
import sys, re, time, itertools, pickle
from pmon import Pn, projections, rank, canon
from termeval import make_eval
sys.setrecursionlimit(10000)

n = int(sys.argv[1]) if len(sys.argv) > 1 else 4
P = Pn(n)

def kerpart(a):  # partition of top points
    return tuple(sorted(tuple(x for x in b if x < n) for b in a if any(x < n for x in b)))
def cokerpart(a):
    return tuple(sorted(tuple(x - n for x in b if x >= n) for b in a if any(x >= n for x in b)))
def cls(a):
    """mu_1-class representative: a itself if rank>=2, else (ker, coker) tag."""
    return a if rank(a, n) >= 2 else ("low", kerpart(a), cokerpart(a))

projs = projections(n)
# representatives of projection classes
reps = {}
for p in projs:
    c = cls(p)
    if c not in reps or rank(p, n) < rank(reps[c], n):
        reps[c] = p
elems = sorted(reps, key=lambda c: (isinstance(c, tuple) and c[0] == "low", str(c)))
idx = {c: i for i, c in enumerate(elems)}
N = len(elems)
tab = [[None] * N for _ in range(N)]
for i, c in enumerate(elems):
    for j, d in enumerate(elems):
        # x * y = y x y
        tab[i][j] = idx[cls(P.prod(reps[d], reps[c], reps[d]))]
print(f"P_{n}/mu_1: projection algebra with {N} elements")
op = lambda x, y: tab[x][y]

# axioms check
ax = ["x * x = x", "(y * x) * x = y * x", "(x * y) * x = y * x",
      "((z * x) * y) * x = z * (y * x)", "(((z * x) * y) * x) * y = (z * x) * y"]
ev = make_eval(op)
for a in ax:
    l, r = a.split("=")
    vs = sorted(set(re.findall(r"[xyz]", a)))
    assert all(ev(l, dict(zip(vs, v))) == ev(r, dict(zip(vs, v))) for v in itertools.product(range(N), repeat=len(vs))), a
print("axioms OK")

HEX = """x1 * x2 != x2 * x3 | x1 * x2 != x3 * x1 |
y1 * y2 != y2 * y3 | y1 * y2 != y3 * y1 |
x1 * y1 != y1 * x1 | x2 * y2 != y2 * x2 | x3 * y3 != y3 * x3 |
y2 * x1 != x1 | x1 * y2 != y2 | y3 * x1 != x1 | x1 * y3 != y3 |
y1 * x2 != x2 | x2 * y1 != y1 | y3 * x2 != x2 | x2 * y3 != y3 |
y1 * x3 != x3 | x3 * y1 != y1 | y2 * x3 != x3 | x3 * y2 != y2 |
x1 * x2 = y1 * y2."""
OCT = """x1 * x2 != x2 * x3 | x1 * x2 != x3 * x4 | x1 * x2 != x4 * x1 |
x1 * x2 != x1 * x3 | x1 * x2 != x2 * x4 |
y1 * y2 != y2 * y3 | y1 * y2 != y3 * y4 | y1 * y2 != y4 * y1 |
y1 * y2 != y1 * y3 | y1 * y2 != y2 * y4 |
x1 * y1 != y1 * x1 | x2 * y2 != y2 * x2 | x3 * y3 != y3 * x3 | x4 * y4 != y4 * x4 |
y2 * x1 != x1 | x1 * y2 != y2 | y4 * x1 != x1 | x1 * y4 != y4 |
y3 * x2 != x2 | x2 * y3 != y3 | y1 * x2 != x2 | x2 * y1 != y1 |
y4 * x3 != x3 | x3 * y4 != y4 | y2 * x3 != x3 | x3 * y2 != y2 |
y1 * x4 != x4 | x4 * y1 != y1 | y3 * x4 != x4 | x4 * y3 != y3 |
x1 * x2 = y1 * y2."""

def parse_clause(text):
    lits = []
    for lit in text.strip().rstrip(".").split("|"):
        lit = lit.strip()
        if "!=" in lit:
            l, r = lit.split("!="); lits.append((l.strip(), r.strip(), True))
        else:
            l, r = lit.split("="); lits.append((l.strip(), r.strip(), False))
    return lits

def search(lits, dom, op, want_all=False, distinct=False):
    ev = make_eval(op)
    vars_ = []
    for l, r, _ in lits:
        for v in re.findall(r"[xy]\d", l + " " + r):
            if v not in vars_: vars_.append(v)
    vars_.sort()
    hyps = [(l, r) for l, r, neg in lits if neg]
    concl = [(l, r) for l, r, neg in lits if not neg]
    stage = [[] for _ in vars_]
    for l, r in hyps:
        vs = set(re.findall(r"[xy]\d", l + " " + r))
        stage[max(vars_.index(v) for v in vs)].append((l, r))
    found = []
    def rec(k, env):
        if k == len(vars_):
            if all(ev(l, env) != ev(r, env) for l, r in concl):
                found.append(dict(env))
            return
        for p in dom:
            if distinct and p in env.values():
                continue
            env[vars_[k]] = p
            if all(ev(l, env) == ev(r, env) for l, r in stage[k]):
                rec(k + 1, env)
            if found and not want_all: return
        del env[vars_[k]]
    rec(0, {})
    return found

def describe(c):
    if isinstance(c, tuple) and c[0] == "low":
        return f"low{c[1]}|{c[2]}"
    return str(c)

def subalgebra(gens):
    S = set(gens); frontier = list(gens)
    while frontier:
        new = []
        for a in list(S):
            for b in frontier:
                for c in (tab[a][b], tab[b][a]):
                    if c not in S:
                        S.add(c); new.append(c)
        frontier = new
    return sorted(S)

for name, text in (("hexagon", HEX), ("octagon", OCT)):
    t = time.time()
    res = search(parse_clause(text), range(N), op, want_all=True, distinct=True)
    print(f"{name}: {len(res)} counterexamples (distinct vertices)  ({time.time()-t:.0f}s)")
    if res:
        e = res[0]
        for v in sorted(e):
            print("   ", v, "=", describe(elems[e[v]]))
        w = op(e["x1"], e["x2"]); z = op(e["y1"], e["y2"])
        print("    w =", describe(elems[w]), " z =", describe(elems[z]))
        sub = subalgebra([e[v] for v in e])
        print(f"    subalgebra generated: {len(sub)} elements")
        # does the hexagon condition hold in that subalgebra?
        r2 = search(parse_clause(HEX), sub, op, distinct=True)
        print(f"    hexagon counterexamples inside it: {len(r2)}")
        if r2:
            for v in sorted(r2[0]): print("      ", v, "=", describe(elems[r2[0][v]]))
    # keep all results for later inspection
    pickle.dump(res, open(f"p{n}mu_{name}.pkl", "wb"))
