T=json.load(open('mk10_T.json')); n=10; th=lambda p,q:T[p][q]
nm='a b c k p q 6 7 8 9'.split()
# theta maps
for x in range(n):
    print(f"theta_{nm[x]}: " + ', '.join(f"{nm[y]}->{nm[th(y,x)]}" for y in range(n) if y!=x and th(y,x)!=x or y==x))
mt=lambda x,y: th(y,x)==x and th(x,y)==y
# all violating instances of (R'_2): a|><|c|><|b, c~x1~x2, x_i identify a,c, y~a, th_{x2}(b)=th_y(b), not a|><|b
viol=[]
for a,c,b,x1,x2,y in itertools.product(range(n),repeat=6):
    if mt(a,c) and mt(c,b) and not mt(a,b) and th(x1,c)==th(c,x1) and th(x1,x2)==th(x2,x1) and th(a,x1)==th(c,x1) and th(a,x2)==th(c,x2) and th(y,a)==th(a,y) and th(b,x2)==th(b,y):
        viol.append(tuple(nm[i] for i in (a,c,b,x1,x2,y)))
print(len(viol),'violating instances:',viol)
# subalgebra generated / irreducibility
def gen(S):
    S=set(S); ch=True
    while ch:
        ch=False
        for x in list(S):
            for y in list(S):
                z=th(x,y)
                if z not in S: S.add(z); ch=True
    return S
irr=[x for x in range(n) if x not in gen(set(range(n))-{x})]
print('irreducible (not generated by the others):',[nm[i] for i in irr])
# maximal subalgebras
maxsub=[]
for x in irr:
    S=gen(set(range(n))-{x}); maxsub.append((x,sorted(S)))
print('maximal subalgebras:',[(nm[x],len(S)) for x,S in maxsub])
