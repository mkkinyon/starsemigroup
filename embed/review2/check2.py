def Pch(n):
    tops = ['a', 'c', 'b'] + [f'x{i}' for i in range(1, n + 1)]
    bots = ['d'] + [f'e{j}' for j in range(n + 1)]
    els = tops + bots
    def th(x, y):  # theta_x(y)
        if x in bots: return x
        if x == 'a': return 'a' if y in ('a', 'c') else 'd'
        if x == 'c': return 'c' if y in ('a', 'b', 'c') else 'e0'
        if x == 'b': return 'b' if y in ('b', 'c') else f'e{n}'
        i = int(x[1:])
        if y == x: return x
        left = {'a', 'c', 'd'} | {f'e{j}' for j in range(i)} | {f'x{j}' for j in range(1, i)}
        right = {f'e{j}' for j in range(i, n + 1)} | {f'x{j}' for j in range(i + 1, n + 1)} | {'b'}
        assert (y in left) != (y in right), (x, y)
        return f'e{i-1}' if y in left else f'e{i}'
    return els, th

def PRp(n):
    tops = ['a', 'c', 'b'] + [f'x{i}' for i in range(1, n + 1)] + ['k']
    bots = ['d'] + [f'e{j}' for j in range(n + 1)]
    els = tops + bots
    _, thch = Pch(n)
    def th(x, y):
        if x in bots: return x
        if x == 'a': return 'a' if y in ('a', 'c') else 'd'
        if x == 'c': return 'c' if y in ('a', 'b', 'c') else 'e0'
        if x == 'b': return 'b' if y in ('b', 'c', 'k', f'x{n}') else f'e{n}'
        if x == 'k':
            if y == 'k': return 'k'
            return {'a': 'd', 'c': 'e0', 'b': f'x{n}', f'e{n}': f'e{n-1}'}.get(y, y)
        i = int(x[1:])
        if y == x: return x
        if i < n:
            return x if y == 'k' else thch(x, y)
        return x if y in ('b', 'k') else f'e{n-1}'
    return els, th

def table(els, th):
    I = {e: i for i, e in enumerate(els)}
    return [[I[th(els[j], els[i])] for j in range(len(els))] for i in range(len(els))]   # T[i][j] = i*j = theta_j(i)

def axioms(T):
    N = range(len(T)); bad = []
    for x in N:
        if T[x][x] != x: bad.append(('PA1', x))
        for y in N:
            if T[T[y][x]][x] != T[y][x]: bad.append(('PA2', x, y))
            if T[T[x][y]][x] != T[y][x]: bad.append(('PA3', x, y))
            for z in N:
                if T[T[T[z][x]][y]][x] != T[z][T[y][x]]: bad.append(('PA4', x, y, z))
                if T[T[T[T[z][x]][y]][x]][y] != T[T[z][x]][y]: bad.append(('PA5', x, y, z))
                if T[z][x] == z and T[z][y] == z and T[x][y] != T[y][x]: bad.append(('Q1', x, y, z))
    return bad

def th_of(T): return lambda x, y: T[y][x]
def comm(T, x, y): return T[x][y] == T[y][x]
def mt(T, x, y): return T[y][x] == x and T[x][y] == y   # x |><| y : theta_x(y) = x and theta_y(x) = y

def W_violations(T, n):
    """instances of (W_n): a|><|c, b|><|c, c~x1~...~xn~b, theta_{xi}(a)=theta_{xi}(c), not a|><|b."""
    N = range(len(T)); out = []
    for a in N:
        for c in N:
            if not mt(T, a, c): continue
            idf = [x for x in N if T[a][x] == T[c][x]]
            adj = {x: [y for y in idf if comm(T, x, y)] for x in idf}
            # chains c ~ x1 ~ ... ~ xn
            layer = {c}
            for _ in range(n):
                layer = {y for x in layer for y in adj[x]}
            for b in N:
                if not mt(T, b, c) or mt(T, a, b): continue
                for xn in layer:
                    if comm(T, xn, b): out.append((a, c, b, xn))
    return out

def Rp_violations(T, n):
    """(R'_n): a|><|c, b|><|c, c~x1~...~xn identifying, y~a, theta_{xn}(b)=theta_y(b), not a|><|b."""
    N = range(len(T)); out = []
    for a in N:
        for c in N:
            if not mt(T, a, c): continue
            idf = [x for x in N if T[a][x] == T[c][x]]
            adj = {x: [y for y in idf if comm(T, x, y)] for x in idf}
            layer = {c}
            for _ in range(n):
                layer = {y for x in layer for y in adj[x]}
            for b in N:
                if not mt(T, b, c) or mt(T, a, b): continue
                for y in N:
                    if not comm(T, y, a): continue
                    for xn in layer:
                        if T[b][xn] == T[b][y]: out.append((a, c, b, xn, y))
    return out

def irreducibles(T):
    N = range(len(T)); out = []
    for r in N:
        gen = set(x for x in N if x != r); closed = True
        # subalgebra generated by the others: closure
        S = set(gen)
        changed = True
        while changed:
            changed = False
            for x in list(S):
                for y in list(S):
                    z = T[x][y]
                    if z not in S: S.add(z); changed = True
        if r not in S: out.append(r)
    return out

