from mace4parse import parse_models
from termeval import make_eval
N,T,c = next(parse_models(open("mace_square13.out").read()))
op=lambda x,y:T[x][y]; ev=make_eval(op)
names={v:k for k,v in c.items()}
def nm(x): return names.get(x,str(x))
le=lambda x,y: T[x][y]==x
print("order relation (x<=y):")
for x in range(N):
    print(f"  {nm(x):3}: below {[nm(y) for y in range(N) if le(x,y) and y!=x]}")
# closure of the constants
S=set(c.values()); 
while True:
    S2=S|{T[x][y] for x in S for y in S}
    if S2==S: break
    S=S2
print("subalgebra generated by constants:", sorted(S), len(S))
# matched / commuting pairs among a_i,b_j
for i in (1,2,3):
    for j in (1,2,3):
        a=c[f"a{i}"]; b=c[f"b{j}"]
        m = T[b][a]==a and T[a][b]==b
        print(f"a{i},b{j}: matched={m}, commute={T[a][b]==T[b][a]}, a*b={T[a][b]}, b*a={T[b][a]}")
w,z=c['cw'],c['cz']
print("m_i:", [T[c[f'a{i}']][c[f'b{i}']] for i in (1,2,3)])
a3,b3=c['a3'],c['b3']
print("u = z*a3 =", T[z][a3], " b3 w b3 = w*b3 =", T[w][b3], " m3 =", T[a3][b3])
print("z a3 z = a3*z =", T[a3][z], " w b3 w = b3*w =", T[b3][w])
print("w*z, z*w:", T[w][z], T[z][w])
# the hexagon found: x3=10,y3=11
print("10 =", [ (nm(x),nm(y)) for x in range(N) for y in range(N) if T[x][y]==10 and x!=10 and y!=10][:8])
print("11 =", [ (nm(x),nm(y)) for x in range(N) for y in range(N) if T[x][y]==11 and x!=11 and y!=11][:8])
# walk Phi(a1): theta_{b3}, theta_{a2}, theta_{b1}, theta_{a3}, theta_{b2}, theta_{a1}
cur=c['a1']; path=[cur]
for s in ['b3','a2','b1','a3','b2','a1']*2:
    cur=T[cur][c[s]]; path.append(cur)
print("walk from a1:", path)
